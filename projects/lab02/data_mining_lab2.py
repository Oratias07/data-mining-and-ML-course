# TODO 3.1: Iterate over K values and display the comparison table
k_values = [1, 3, 5, 9, 17, 33]
n_train = X_train.shape[0]
results = []

for k in k_values:
    if k > n_train:
        print(f"K={k} skipped: exceeds number of training samples ({n_train})")
        continue
    clf = KNeighborsClassifier(n_neighbors=k)
    clf.fit(X_train, y_train)
    results.append({
        "K": k,
        "Train Accuracy": accuracy_score(y_train, clf.predict(X_train)),
        "Test Accuracy": accuracy_score(y_test, clf.predict(X_test)),
    })

results_df = pd.DataFrame(results).round(4)
display(results_df)

best_k = int(results_df.loc[results_df["Test Accuracy"].idxmax(), "K"])
