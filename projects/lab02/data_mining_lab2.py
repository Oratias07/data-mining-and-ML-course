"""### 3. Bag-of-Words Representation & Stratified Split"""

# Bag-of-Words with standard English stop words removed
vectorizer = CountVectorizer(stop_words="english")
X_bow = vectorizer.fit_transform(df["text"])
y = df["label"]

print(f"Vocabulary size (with stop words removed): {len(vectorizer.vocabulary_)}")

# Stratified 75% Train / 25% Test split
X_train, X_test, y_train, y_test = train_test_split(
    X_bow, y, test_size=0.25, random_state=42, stratify=y
)
print(f"Train shape: {X_train.shape}, Test shape: {X_test.shape}")

"""### 4. Baseline KNN Model & Accuracy Evaluation (Demo)"""

knn_demo = KNeighborsClassifier(n_neighbors=5)
knn_demo.fit(X_train, y_train)

y_pred_demo = knn_demo.predict(X_test)
acc_demo = accuracy_score(y_test, y_pred_demo)
print(f"Baseline KNN (K=5) Test Accuracy: {acc_demo:.4f}")

"""### 5. ROC Curve Demo"""

y_probs_demo = knn_demo.predict_proba(X_test)[:, 1]
fpr_demo, tpr_demo, _ = roc_curve(y_test, y_probs_demo)
auc_demo = roc_auc_score(y_test, y_probs_demo)

plt.figure(figsize=(6, 5))
plt.plot(fpr_demo, tpr_demo, label=f"Demo K=5 (AUC = {auc_demo:.2f})")
plt.plot([0, 1], [0, 1], "k--", label="Random Guess")
plt.xlabel("False Positive Rate (FPR)")
plt.ylabel("True Positive Rate (TPR)")
plt.title("ROC Curve Demo")
plt.legend()
